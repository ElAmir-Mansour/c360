// RenderEvidencePDF renders an EvidenceReport as a real, regulator-ready PDF
// document using gofpdf (genuine PDF generation, not an HTML stand-in). It
// preserves the legacy (English) signature; RenderEvidencePDFLocalized is the
// locale-aware entrypoint. The document carries every section the contract
// requires — the runbook executed, RTO vs RTA, approvals, integrity-check
// results, and the full timeline — each populated from the report's real data.
func RenderEvidencePDF(rep *EvidenceReport) ([]byte, error) {
	return RenderEvidencePDFLocalized(rep, localeEN)
}

// RenderEvidencePDFLocalized renders the evidence report as a PDF in the requested
// locale, resolving every label through evidenceLabels and right-aligning cells for
// Arabic. See the "gofpdf LIMITATION" / "HTML->PDF path" notes above: for a shaped,
// customer-/regulator-facing Arabic PDF use RenderEvidenceHTML + a headless-Chrome
// converter. This function is the label-catalog + locale threading + alignment
// scaffolding.
func RenderEvidencePDFLocalized(rep *EvidenceReport, locale string) ([]byte, error) {
	locale = normalizeReportLocale(locale)
	align := alignFor(locale)
	lbl := func(key string) string { return localizeLabel(evidenceLabels, key, locale) }

	pdf := gofpdf.New("P", "mm", "A4", "")
	pdf.SetTitle(lbl("doc_title"), false)
	pdf.SetAutoPageBreak(true, pdfMargin)
	pdf.AddPage()

	// --- Title block. --------------------------------------------------------
	pdf.SetFont("Helvetica", "B", 16)
	pdf.CellFormat(pdfContentWidth, 9, lbl("doc_title"), "", 1, align, false, 0, "")
	pdf.SetFont("Helvetica", "", 9)
	pdf.SetTextColor(90, 90, 90)
	pdf.CellFormat(pdfContentWidth, 5, lbl("generated")+" "+fmtTime(rep.GeneratedAt)+" "+lbl("utc"), "", 1, align, false, 0, "")
	pdf.SetTextColor(0, 0, 0)
	pdf.Ln(3)

	// --- Event identity. -----------------------------------------------------
	pdfSectionHeading(pdf, align, lbl("sec_event"))
	pdfKeyValue(pdf, align, lbl("event_id"), rep.EventID.String())
	pdfKeyValue(pdf, align, lbl("sub_solution"), labelSubSolution(rep.SubSolution, locale))
	if rep.ApplicationName != "" || rep.ApplicationKey != "" {
		pdfKeyValue(pdf, align, lbl("application"), joinAppLabel(rep.ApplicationName, rep.ApplicationKey))
	}
	if rep.RecoveryTier != "" {
		pdfKeyValue(pdf, align, lbl("recovery_tier"), rep.RecoveryTier)
	}
	pdf.Ln(2)

	pdfSectionHeading(pdf, align, lbl("sec_proof"))
	if rep.Proof == nil {
		pdfMuted(pdf, align, lbl("no_proof"))
	} else {
		pdfKeyValue(pdf, align, lbl("proof_status"), rep.Proof.Status)
		if rep.Proof.Reason != "" {
			pdfKeyValue(pdf, align, lbl("proof_reason"), rep.Proof.Reason)
		}
		pdfKeyValue(pdf, align, lbl("payload_hash"), rep.Proof.PayloadHash)
		pdfKeyValue(pdf, align, lbl("hash_algorithm"), rep.Proof.PayloadHashAlgorithm)
		if rep.Proof.GeneratedBy != "" {
			pdfKeyValue(pdf, align, lbl("generated_by"), rep.Proof.GeneratedBy)
		}
		pdfKeyValue(pdf, align, lbl("signature"), rep.Proof.Signature.Status)
		if rep.Proof.HashChain != nil {
			pdfKeyValue(pdf, align, lbl("ledger"), rep.Proof.HashChain.Ledger)
			pdfKeyValue(pdf, align, lbl("ledger_seq"), strconv.FormatInt(rep.Proof.HashChain.Seq, 10))
			pdfKeyValue(pdf, align, lbl("previous_hash"), rep.Proof.HashChain.PreviousHash)
			pdfKeyValue(pdf, align, lbl("entry_hash"), rep.Proof.HashChain.EntryHash)
			pdfKeyValue(pdf, align, lbl("root_hash"), rep.Proof.HashChain.RootHash)
		}
		if rep.Proof.Anchor != nil {
			pdfKeyValue(pdf, align, lbl("anchor_status"), rep.Proof.Anchor.Status)
			if rep.Proof.Anchor.MerkleRoot != "" {
				pdfKeyValue(pdf, align, lbl("merkle_root"), rep.Proof.Anchor.MerkleRoot)
			}
			if rep.Proof.Anchor.WORMObjectKey != "" {
				pdfKeyValue(pdf, align, lbl("worm_object"), rep.Proof.Anchor.WORMObjectKey)
				pdfKeyValue(pdf, align, lbl("worm_version"), rep.Proof.Anchor.WORMVersionID)
			}
		}
	}
	pdf.Ln(2)

	// --- Runbook executed + RTO vs RTA. --------------------------------------
	pdfSectionHeading(pdf, align, lbl("sec_runbook"))
	if rep.RunbookExecution != nil {
		e := rep.RunbookExecution
		pdfKeyValue(pdf, align, lbl("runbook"), e.RunbookName)
		pdfKeyValue(pdf, align, lbl("run_id"), e.RunID.String())
		pdfKeyValue(pdf, align, lbl("mode"), e.Mode)
		pdfKeyValue(pdf, align, lbl("status"), e.Status)
		pdfKeyValue(pdf, align, lbl("started"), fmtTime(e.StartedAt))
		pdfKeyValue(pdf, align, lbl("completed"), fmtTimePtr(e.CompletedAt))
		pdfKeyValue(pdf, align, lbl("rto_target"), strconv.Itoa(e.RTOTargetSeconds))
		pdfKeyValue(pdf, align, lbl("rta_actual"), fmtIntPtr(e.RTAActualSeconds))
		if e.RTABreach {
			pdf.SetTextColor(176, 0, 32)
			pdfKeyValue(pdf, align, lbl("rto_outcome"), lbl("rto_breached")+" "+strconv.Itoa(e.BreachSeconds)+lbl("seconds_suffix"))
			pdf.SetTextColor(0, 0, 0)
		} else if e.RTAActualSeconds != nil {
			pdf.SetTextColor(0, 120, 60)
			pdfKeyValue(pdf, align, lbl("rto_outcome"), lbl("rto_within"))
			pdf.SetTextColor(0, 0, 0)
		} else {
			pdfKeyValue(pdf, align, lbl("rto_outcome"), lbl("rto_uncaptured"))
		}
	} else {
		pdfMuted(pdf, align, lbl("no_runbook"))
	}
	pdf.Ln(2)

	// --- Approvals. ----------------------------------------------------------
	pdfSectionHeading(pdf, align, lbl("sec_approvals"))
	if len(rep.Approvals) == 0 {
		pdfMuted(pdf, align, lbl("no_approvals"))
	} else {
		for i := range rep.Approvals {
			a := &rep.Approvals[i]
			line := fmtTime(a.ApprovedAt) + "  —  " + a.Approver + " (" + a.Action + ")"
			pdfBullet(pdf, align, line)
			if a.ScanID != "" {
				pdfBulletSub(pdf, align, lbl("pinned_scan")+" "+a.ScanID)
			}
			if a.Note != "" {
				pdfBulletSub(pdf, align, lbl("note_prefix")+" "+a.Note)
			}
		}
	}
	pdf.Ln(2)

	// --- Integrity-check results (cyber recovery). ---------------------------
	pdfSectionHeading(pdf, align, lbl("sec_integrity"))
	if len(rep.IntegrityChecks) == 0 {
		pdfMuted(pdf, align, lbl("no_integrity"))
	} else {
		for i := range rep.IntegrityChecks {
			c := &rep.IntegrityChecks[i]
			verdict := c.Verdict
			if c.Passed {
				pdf.SetTextColor(0, 120, 60)
			} else {
				pdf.SetTextColor(176, 0, 32)
			}
			pdfBullet(pdf, align, fmtTime(c.CheckedAt)+"  —  "+verdict)
			pdf.SetTextColor(0, 0, 0)
			if c.ScanID != "" {
				pdfBulletSub(pdf, align, lbl("scan_prefix")+" "+c.ScanID)
			}
			if c.Detail != "" {
				pdfBulletSub(pdf, align, c.Detail)
			}
		}
	}
	pdf.Ln(2)

	// --- Full timeline. ------------------------------------------------------
	pdfSectionHeading(pdf, align, lbl("sec_timeline"))
	if len(rep.Timeline) == 0 {
		pdfMuted(pdf, align, lbl("no_timeline"))
	} else {
		for i := range rep.Timeline {
			t := &rep.Timeline[i]
			pdf.SetFont("Helvetica", "B", 8)
			pdf.CellFormat(36, pdfLineHeight, fmtTime(t.At), "", 0, align, false, 0, "")
			pdf.SetFont("Helvetica", "", 8)
			line := t.Action
			if t.Actor != "" {
				line += "  ·  " + t.Actor
			}
			pdf.MultiCell(pdfContentWidth-36, pdfLineHeight, line, "", align, false)
			if t.Summary != "" {
				pdf.SetX(pdfMargin + 36)
				pdf.SetTextColor(90, 90, 90)
				pdf.SetFont("Helvetica", "I", 8)
				pdf.MultiCell(pdfContentWidth-36, pdfLineHeight, t.Summary, "", align, false)
				pdf.SetTextColor(0, 0, 0)
			}
		}
	}

	if err := pdf.Error(); err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if err := pdf.Output(&buf); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// --- PDF layout helpers -----------------------------------------------------

func pdfSectionHeading(pdf *gofpdf.Fpdf, align, title string) {
	pdf.SetFont("Helvetica", "B", 11)
	pdf.SetFillColor(232, 240, 236)
	pdf.CellFormat(pdfContentWidth, 7, title, "", 1, align, true, 0, "")
	pdf.Ln(1)
}

func pdfKeyValue(pdf *gofpdf.Fpdf, align, key, value string) {
	pdf.SetFont("Helvetica", "B", 9)
	pdf.CellFormat(45, pdfLineHeight, key, "", 0, align, false, 0, "")
	pdf.SetFont("Helvetica", "", 9)
	pdf.MultiCell(pdfContentWidth-45, pdfLineHeight, valueOrDash(value), "", align, false)
}

func pdfBullet(pdf *gofpdf.Fpdf, align, text string) {
	pdf.SetFont("Helvetica", "", 9)
	pdf.CellFormat(4, pdfLineHeight, "-", "", 0, align, false, 0, "")
	pdf.MultiCell(pdfContentWidth-4, pdfLineHeight, text, "", align, false)
}

func pdfBulletSub(pdf *gofpdf.Fpdf, align, text string) {
	pdf.SetX(pdfMargin + 6)
	pdf.SetFont("Helvetica", "I", 8)
	pdf.SetTextColor(90, 90, 90)
	pdf.MultiCell(pdfContentWidth-6, pdfLineHeight, text, "", align, false)
	pdf.SetTextColor(0, 0, 0)
}

func pdfMuted(pdf *gofpdf.Fpdf, align, text string) {
	pdf.SetFont("Helvetica", "I", 9)
	pdf.SetTextColor(120, 120, 120)
	pdf.MultiCell(pdfContentWidth, pdfLineHeight, text, "", align, false)
	pdf.SetTextColor(0, 0, 0)
}

func valueOrDash(v string) string {
	if v == "" {
		return "—"
	}
	return v
}

func joinAppLabel(name, key string) string {
	switch {
	case name != "" && key != "":
		return name + " (" + key + ")"
	case name != "":
		return name
	default:
		return key
	}
}

func labelSubSolution(s, locale string) string {
	switch s {
	case AuditSubSolutionITDR:
		return localizeLabel(evidenceLabels, "subsol_it_dr", locale)
	case AuditSubSolutionCloudDR:
		return localizeLabel(evidenceLabels, "subsol_cloud_dr", locale)
	case AuditSubSolutionCyberRecovery:
		return localizeLabel(evidenceLabels, "subsol_cyber", locale)
	default:
		return s
	}
}

// RenderEvidenceHTML renders the evidence report as a self-contained HTML document
// in the requested locale. It is the "HTML half" of the recommended HTML->PDF path:
// unlike gofpdf, a browser engine shapes Arabic glyphs and applies bidi/RTL from the
// dir="rtl" attribute, so this HTML converts to a correct Arabic PDF via headless
// Chrome (chromedp) / wkhtmltopdf. The inline RTL styling mirrors the notification
// email RTL CSS (dir/text-align driven by locale). Wiring the actual HTML->PDF
// converter is the deferred follow-up (it needs an approved headless-Chrome binary
// dependency); this function makes the localized, RTL-correct source ready to feed it.
func RenderEvidenceHTML(rep *EvidenceReport, locale string) ([]byte, error) {
	locale = normalizeReportLocale(locale)
	lbl := func(key string) string { return localizeLabel(evidenceLabels, key, locale) }
	dir := "ltr"
	textAlign := "left"
	if locale == localeAR {
		dir = "rtl"
		textAlign = "right"
	}

	type kvRow struct{ K, V string }
	type section struct {
		Title string
		Rows  []kvRow
		Muted string
	}
	data := struct {
		Lang      string
		Dir       string
		TextAlign string
		Title     string
		Generated string
		Sections  []section
	}{
		Lang:      locale,
		Dir:       dir,
		TextAlign: textAlign,
		Title:     lbl("doc_title"),
		Generated: lbl("generated") + " " + fmtTime(rep.GeneratedAt) + " " + lbl("utc"),
	}

	event := section{Title: lbl("sec_event"), Rows: []kvRow{
		{lbl("event_id"), rep.EventID.String()},
		{lbl("sub_solution"), labelSubSolution(rep.SubSolution, locale)},
	}}
	if rep.ApplicationName != "" || rep.ApplicationKey != "" {
		event.Rows = append(event.Rows, kvRow{lbl("application"), joinAppLabel(rep.ApplicationName, rep.ApplicationKey)})
	}
	if rep.RecoveryTier != "" {
		event.Rows = append(event.Rows, kvRow{lbl("recovery_tier"), rep.RecoveryTier})
	}
	data.Sections = append(data.Sections, event)

	runbook := section{Title: lbl("sec_runbook")}
	if rep.RunbookExecution != nil {
		e := rep.RunbookExecution
		runbook.Rows = []kvRow{
			{lbl("runbook"), e.RunbookName},
			{lbl("run_id"), e.RunID.String()},
			{lbl("mode"), e.Mode},
			{lbl("status"), e.Status},
			{lbl("started"), fmtTime(e.StartedAt)},
			{lbl("completed"), fmtTimePtr(e.CompletedAt)},
			{lbl("rto_target"), strconv.Itoa(e.RTOTargetSeconds)},
			{lbl("rta_actual"), fmtIntPtr(e.RTAActualSeconds)},
		}
		switch {
		case e.RTABreach:
			runbook.Rows = append(runbook.Rows, kvRow{lbl("rto_outcome"), lbl("rto_breached") + " " + strconv.Itoa(e.BreachSeconds) + lbl("seconds_suffix")})
		case e.RTAActualSeconds != nil:
			runbook.Rows = append(runbook.Rows, kvRow{lbl("rto_outcome"), lbl("rto_within")})
		default:
			runbook.Rows = append(runbook.Rows, kvRow{lbl("rto_outcome"), lbl("rto_uncaptured")})
		}
	} else {
		runbook.Muted = lbl("no_runbook")
	}
	data.Sections = append(data.Sections, runbook)

	const tmpl = `<!DOCTYPE html>
<html lang="{{.Lang}}" dir="{{.Dir}}">
<head><meta charset="utf-8"><title>{{.Title}}</title>
<style>
body{font-family:Arial, sans-serif; color:#111; margin:24px; text-align:{{.TextAlign}}; direction:{{.Dir}};}
h1{font-size:20px; margin:0 0 4px;} .muted{color:#777; font-size:12px;}
h2{font-size:14px; background:#e8f0ec; padding:6px 10px; margin:18px 0 8px;}
table{width:100%; border-collapse:collapse;} td{padding:4px 8px; vertical-align:top; font-size:12px;}
td.k{font-weight:bold; width:220px; color:#333;}
</style></head>
<body>
<h1>{{.Title}}</h1>
<div class="muted">{{.Generated}}</div>
{{range .Sections}}<h2>{{.Title}}</h2>
{{if .Muted}}<div class="muted">{{.Muted}}</div>{{else}}<table>{{range .Rows}}<tr><td class="k">{{.K}}</td><td>{{.V}}</td></tr>{{end}}</table>{{end}}
{{end}}
</body></html>`

	t, err := template.New("evidence").Parse(tmpl)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if err := t.Execute(&buf, data); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}
