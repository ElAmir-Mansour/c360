/**
 * useAdminT resolves the full admin label tree against the active locale.
 * Components destructure the group they need, e.g.
 *   const { users: t } = useAdminT();
 */
export function useAdminT(): AdminLabels {
  const { locale } = useLocaleOrDefault();
  return useMemo(() => resolveAdminLabels(locale), [locale]);
}

