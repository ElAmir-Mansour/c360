// PDF layout constants (A4, mm). Kept explicit so the document is reproducible.
const (
	pdfMargin       = 15.0
	pdfContentWidth = 210.0 - 2*pdfMargin // A4 width (210mm) minus left+right margin
	pdfLineHeight   = 5.0
)

// Report localization notes
// ==========================
//
// Report string LITERALS are routed through evidenceLabels — a per-report label
// table keyed by a stable slug and resolved by the report's locale — so the same
// generator can emit an English or an Arabic evidence report. RenderEvidencePDFLocalized
// is the locale-aware entrypoint; RenderEvidencePDF keeps the legacy no-locale
// signature (English) so existing callers stay unchanged.
//
// gofpdf LIMITATION (do not "fix" here): the vendored gofpdf ships only the core
// Latin PDF fonts and performs NO Arabic glyph shaping or bidi reordering. Feeding
// it Arabic strings produces missing-glyph / visually-broken output. The locale
// threading + right-alignment ('R') implemented here is the SAFE, compiling
// scaffolding only.
//
// HTML->PDF path (recommended for customer-/regulator-facing Arabic): render the
// report as HTML with dir="rtl" and convert it with headless Chrome (chromedp) or
// wkhtmltopdf, which get RTL + Arabic shaping for free from the browser engine and
// let us reuse the notification-service email RTL CSS
// (internal/notification/service/template_service.go baseLayoutTemplate). The HTML
// half of that path is implemented and ready in RenderEvidenceHTML below; the only
// remaining follow-up is wiring the (heavier, binary-dependent) HTML->PDF converter
// behind the same entrypoint once a headless-Chrome dependency is approved. gofpdf
// stays for internal/English artifacts.

const (
	localeEN = "en"
	localeAR = "ar"
)

// reportLocaleDefault is the tenant/product default locale for customer-/regulator-
// facing reports (Watheeq / KSA tenants default to Arabic). It is applied when a
// caller passes an empty locale. The legacy RenderEvidencePDF wrapper passes localeEN
// explicitly so its output never regresses while the gofpdf Arabic-shaping gap is open.
const reportLocaleDefault = localeAR

// normalizeReportLocale collapses an arbitrary locale tag to the two supported
// report locales, defaulting to the tenant/product default when unset.
func normalizeReportLocale(locale string) string {
	switch locale {
	case localeAR:
		return localeAR
	case localeEN:
		return localeEN
	case "":
		return reportLocaleDefault
	default:
		if len(locale) >= 2 && locale[:2] == "ar" {
			return localeAR
		}
		return localeEN
	}
}

// alignFor returns the gofpdf cell alignment for a locale ("R" right-aligns Arabic
// text, "L" left-aligns Latin).
func alignFor(locale string) string {
	if locale == localeAR {
		return "R"
	}
	return "L"
}

// localizeLabel resolves a report label slug to text in the requested locale via
// forms.LocalizedText (the canonical backend bilingual string type, with built-in
// other-locale fallback). An unknown slug falls back to the slug itself.
func localizeLabel(cat map[string]forms.LocalizedText, key, locale string) string {
	if lt, ok := cat[key]; ok {
		return lt.Localize(locale)
	}
	return key
}

