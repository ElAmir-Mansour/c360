type Join<Key, Path> = Key extends string
  ? Path extends string
    ? `${Key}.${Path}`
    : never
  : never;

export type MessageKey = {
  [Key in keyof AppMessages & string]: AppMessages[Key] extends string
    ? Key
    : Join<
        Key,
        {
          [NestedKey in keyof AppMessages[Key] & string]: AppMessages[Key][NestedKey] extends string
            ? NestedKey
            : Join<
                NestedKey,
                {
                  [LeafKey in keyof AppMessages[Key][NestedKey] & string]: AppMessages[Key][NestedKey][LeafKey] extends string
                    ? LeafKey
                    : Join<
                        LeafKey,
                        keyof AppMessages[Key][NestedKey][LeafKey] & string
                      >;
                }[keyof AppMessages[Key][NestedKey] & string]
              >;
        }[keyof AppMessages[Key] & string]
      >;
}[keyof AppMessages & string];

// ---------------------------------------------------------------------------
// Pseudo-locale (build-time localization QA)
//
// Usage: set `NEXT_PUBLIC_PSEUDO_LOCALE=1`, then select locale `pseudo` (the
// flag makes `normalizeLocale`/`getMessages` accept it — see ../i18n). The
// `en` tree is transformed at runtime: Latin vowels are accented, each visible
// string is padded ~+40% with `~` and wrapped in `[!! … !!]`. `{token}`
// interpolation spans and `${…}` template spans are passed through verbatim so
// runtime interpolation still resolves. On the pseudo page: any plain,
// unbracketed English string is a HARDCODED literal that skipped i18n, and the
// padding surfaces truncation / expansion overflow. Off by default — the
// typed catalogue (`ar`/`en`), `AppLocale`, and `MESSAGES` are untouched.
// ---------------------------------------------------------------------------

const PSEUDO_ACCENTS: Record<string, string> = {
  a: 'ä', e: 'é', o: 'ö', i: 'ï', u: 'ü',
  A: 'Ä', E: 'É', O: 'Ö', I: 'Ï', U: 'Ü',
};

// Split delimiter (global, capturing): keeps `${…}` and `{token}` spans as
// standalone parts. `${…}` is first in the alternation so its `$` is consumed
// rather than accented. Anchored twin tests whether a part IS such a span.
const PSEUDO_SPAN_SPLIT = /(\$\{[^}]*\}|\{[^}]*\})/g;
const PSEUDO_SPAN_MATCH = /^(?:\$\{[^}]*\}|\{[^}]*\})$/;

function accentPseudo(segment: string): string {
  let out = '';
  for (const ch of segment) out += PSEUDO_ACCENTS[ch] ?? ch;
  return out;
}

function pseudoString(source: string): string {
  const accented = source
    .split(PSEUDO_SPAN_SPLIT)
    .map((part) => (part && PSEUDO_SPAN_MATCH.test(part) ? part : accentPseudo(part)))
    .join('');
  // Pad by ~40% of the visible (token-stripped) length to expose overflow.
  const visibleLength = source.replace(PSEUDO_SPAN_SPLIT, '').length;
  const padCount = Math.ceil(visibleLength * 0.4);
  const padding = padCount > 0 ? ` ${'~'.repeat(padCount)}` : '';
  return `[!! ${accented}${padding} !!]`;
}

function pseudoTransform<T>(node: T): T {
  if (typeof node === 'string') return pseudoString(node) as unknown as T;
  if (node && typeof node === 'object') {
    const out: Record<string, unknown> = {};
    for (const [key, value] of Object.entries(node as Record<string, unknown>)) {
      out[key] = pseudoTransform(value);
    }
    return out as T;
  }
  // Non-string leaves (functions, numbers) pass through untouched.
  return node;
}

let pseudoMessagesCache: AppMessages | null = null;

/** Lazily build (and memoize) the pseudo catalogue from the `en` tree. */
function getPseudoMessages(): AppMessages {
  if (!pseudoMessagesCache) pseudoMessagesCache = pseudoTransform(en);
  return pseudoMessagesCache;
}

export function getMessages(locale: string | null | undefined = DEFAULT_LOCALE): AppMessages {
  const normalized = normalizeLocale(locale) ?? DEFAULT_LOCALE;
  if (normalized === PSEUDO_LOCALE) return getPseudoMessages();
  return MESSAGES[normalized];
}

export function readMessage(messages: AppMessages, key: MessageKey): string {
  const value = key.split('.').reduce<unknown>((current, segment) => {
    if (!current || typeof current !== 'object') return undefined;
    return (current as Record<string, unknown>)[segment];
  }, messages);

  return typeof value === 'string' ? value : key;
}

export function createTranslator(locale: string | null | undefined = DEFAULT_LOCALE) {
  const messages = getMessages(locale);
  return (key: MessageKey) => readMessage(messages, key);
}

export function listMessageKeys(messages: AppMessages = getMessages()): string[] {
  const keys: string[] = [];

  function walk(value: Record<string, unknown>, prefix: string) {
    for (const [key, nestedValue] of Object.entries(value)) {
      const path = prefix ? `${prefix}.${key}` : key;
      if (typeof nestedValue === 'string') {
        keys.push(path);
      } else if (nestedValue && typeof nestedValue === 'object') {
        walk(nestedValue as Record<string, unknown>, path);
      }
    }
  }

  walk(messages as unknown as Record<string, unknown>, '');
  return keys.sort();
}
