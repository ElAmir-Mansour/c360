/**
 * Bilingual (English + Modern Standard Arabic) label bundles for the Clario360
 * Admin console (users, roles, audit, AI governance, api-keys, billing,
 * invitations, notifications, tenants, settings, workflows).
 *
 * THE BILINGUAL CONTRACT:
 *   - Every label group is a `{ en, ar }` bundle holding two FULL, same-shaped
 *     copies of the label object — English in `en`, professional Saudi-register
 *     MSA in `ar`.
 *   - Components NEVER receive the bundle; they call a hook (`useAdminT`) which
 *     resolves the bundle against the active locale and returns the resolved
 *     object `T`.
 *   - Western digits, interpolation params and established acronyms
 *     (MFA, API, AI, SLA, RTO, RPO, WORM, JSON, CSV) are preserved across both
 *     locales.
 *   - Resolution defaults to the configured default locale when no
 *     LocaleProvider is mounted (mirrors `useLocaleOrDefault`), keeping isolated
 *     unit tests rendering predictably.
 */
