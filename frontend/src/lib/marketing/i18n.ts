/* ============================================================
   RESOLVERS — merge AR text onto the EN record (icons/metrics
   preserved via spread) with per-field EN fallback.
   ============================================================ */
export interface LocalizedAppText {
  readonly role: string;
  readonly short: string;
  readonly hero: string;
  readonly desc: string;
  readonly bench: string;
  readonly specs: readonly MarketingSpec[];
  readonly modules: readonly MarketingModule[];
  readonly flow: readonly MarketingFlowStep[];
}

export function localizeMarketingApp(
  app: Pick<
    MarketingApp,
    'id' | 'role' | 'short' | 'hero' | 'desc' | 'bench' | 'specs' | 'modules' | 'flow'
  >,
  locale: MarketingLocale,
): LocalizedAppText {
  const en: LocalizedAppText = {
    role: app.role,
    short: app.short,
    hero: app.hero,
    desc: app.desc,
    bench: app.bench,
    specs: app.specs,
    modules: app.modules,
    flow: app.flow,
  };
  if (locale !== 'ar') return en;
  const ar = APP_AR[app.id];
  if (!ar) return en;
  return {
    role: ar.role || en.role,
    short: ar.short || en.short,
    hero: ar.hero || en.hero,
    desc: ar.desc || en.desc,
    bench: ar.bench || en.bench,
    specs: app.specs.map((s, i) => ({
      metric: ar.specs[i]?.metric ?? s.metric,
      description: ar.specs[i]?.description ?? s.description,
    })),
    modules: app.modules.map((m, i) => ({
      ...m,
      title: ar.modules[i]?.title ?? m.title,
      description: ar.modules[i]?.description ?? m.description,
    })),
    flow: app.flow.map((f, i) => ({
      ...f,
      step: ar.flow[i]?.step ?? f.step,
      description: ar.flow[i]?.description ?? f.description,
    })),
  };
}

