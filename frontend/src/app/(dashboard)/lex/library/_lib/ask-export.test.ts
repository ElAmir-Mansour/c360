import { describe, it, expect } from 'vitest';
import {
  formatAskTurnForExport,
  toExportFileStem,
  type AskExportLabels,
} from './ask-export';
import type { LexReferenceAskCitation } from '@/types/suites';

const labels: AskExportLabels = {
  exportQuestionLabel: 'Question',
  exportAnswerLabel: 'Answer',
  exportSourcesLabel: 'Sources',
  exportPageLabel: (page) => `page ${page}`,
  exportGeneratedBy: (model) => `Generated by ${model}`,
};

function citation(over: Partial<LexReferenceAskCitation> = {}): LexReferenceAskCitation {
  return {
    doc_id: 'doc-1',
    title_ar: 'نظام العمل',
    title_en: 'Labour Law',
    snippet: 'Article text…',
    page: 12,
    score: 0.9,
    ...over,
  };
}

describe('formatAskTurnForExport', () => {
  it('includes the question, answer, and cited sources with pages', () => {
    const out = formatAskTurnForExport(
      {
        question: 'What are the notice periods?',
        answer: 'The notice period is 30 days.',
        citations: [citation()],
        model: 'watheeq-legal-1',
      },
      'en',
      labels,
    );
    expect(out).toContain('## Question');
    expect(out).toContain('What are the notice periods?');
    expect(out).toContain('## Answer');
    expect(out).toContain('The notice period is 30 days.');
    expect(out).toContain('## Sources');
    expect(out).toContain('1. Labour Law (page 12)');
    expect(out).toContain('> Article text…');
    expect(out).toContain('Generated by watheeq-legal-1');
  });

  it('resolves Arabic titles in the ar locale', () => {
    const out = formatAskTurnForExport(
      { question: 'س', answer: 'ج', citations: [citation()] },
      'ar',
      labels,
    );
    expect(out).toContain('نظام العمل');
  });

  it('omits the Sources section when there are no citations', () => {
    const out = formatAskTurnForExport(
      { question: 'q', answer: 'a', citations: [] },
      'en',
      labels,
    );
    expect(out).not.toContain('## Sources');
  });

  it('omits the page suffix when a citation has no page', () => {
    const out = formatAskTurnForExport(
      { question: 'q', answer: 'a', citations: [citation({ page: null })] },
      'en',
      labels,
    );
    expect(out).toContain('1. Labour Law');
    expect(out).not.toContain('(page');
  });
});

describe('toExportFileStem', () => {
  it('appends a slugified question to the base', () => {
    expect(toExportFileStem('answer', 'Notice periods?')).toBe('answer-Notice-periods');
  });

  it('falls back to the base when the question has no usable characters', () => {
    expect(toExportFileStem('answer', '!!!')).toBe('answer');
  });

  it('keeps Arabic script in the slug', () => {
    expect(toExportFileStem('إجابة', 'مدة الإشعار')).toBe('إجابة-مدة-الإشعار');
  });
});
